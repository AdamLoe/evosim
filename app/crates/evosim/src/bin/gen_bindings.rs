//! Codegen: emit the TS mirror of the slider table, control-SAB layout, and
//! LOD constants.
//!
//! Run:
//!   cargo run --bin gen-bindings
//!
//! Writes:
//!   src/web/src/generated/slider-ids.ts
//!   src/web/src/generated/control-sab.ts
//!   src/web/src/generated/lod-constants.ts
//!
//! A unit test (`bindings_in_sync`) in this binary's source compares the
//! current on-disk TS against what this binary would emit; CI fails if they
//! diverge. Devs run this binary to update the TS files.

use std::path::PathBuf;

use evosim::control_sab::{
    CONTROL_SAB_BYTES, CTRL_CAMERA_CX_BITS, CTRL_CAMERA_CY_BITS, CTRL_CAMERA_VIEWPORT_H,
    CTRL_CAMERA_VIEWPORT_W, CTRL_CAMERA_ZOOM_BITS, CTRL_CONTROL_EPOCH, CTRL_CURRENT_SLOT,
    CTRL_FUTEX, CTRL_I32_REGION_LEN, CTRL_INSPECT_REQ_EPOCH, CTRL_INSPECT_REQ_ID_HI,
    CTRL_INSPECT_REQ_ID_LO, CTRL_INSPECT_REQ_KIND, CTRL_INSPECT_REQ_TOL_BITS,
    CTRL_INSPECT_REQ_WX_BITS, CTRL_INSPECT_REQ_WY_BITS, CTRL_INSPECT_RESP_EPOCH,
    CTRL_INSPECT_RESP_LEN, CTRL_INSPECT_RESP_REQ_EPOCH, CTRL_NN_STATS_EPOCH, CTRL_NN_STATS_LEN,
    CTRL_PAUSED, CTRL_PROFILE_CLEAR_EPOCH, CTRL_PROFILE_REPORT_EPOCH, CTRL_PROFILE_REPORT_LEN,
    CTRL_PROFILE_WINDOW_MS, CTRL_RESET_JANK_EPOCH, CTRL_SEQ, CTRL_SLIDERS_BASE,
    CTRL_SPECIES_TABLE_EPOCH, CTRL_SPECIES_TABLE_LEN, CTRL_TARGET_TPS_BITS, INSPECT_RESP_CAP,
    INSPECT_RESP_OFFSET, NN_STATS_CAP, NN_STATS_OFFSET, PROFILE_REPORT_CAP, PROFILE_REPORT_OFFSET,
    SPECIES_TABLE_CAP, SPECIES_TABLE_OFFSET,
};
use evosim::{GRASS_LOD_BUDGET_AXIS, SLIDER_COUNT, SLIDER_NAMES};

fn main() {
    // CARGO_MANIFEST_DIR is `src/crates/evosim`; the TS app is at `src/web`,
    // so the generated mirror lives two levels up under `web/`.
    let crate_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let gen_dir = crate_dir.join("../../web/src/generated");
    std::fs::create_dir_all(&gen_dir).expect("create src/web/src/generated/");

    let slider_ids = render_slider_ids();
    let control_sab = render_control_sab();
    let lod_constants = render_lod_constants();

    std::fs::write(gen_dir.join("slider-ids.ts"), &slider_ids).expect("write slider-ids.ts");
    std::fs::write(gen_dir.join("control-sab.ts"), &control_sab).expect("write control-sab.ts");
    std::fs::write(gen_dir.join("lod-constants.ts"), &lod_constants)
        .expect("write lod-constants.ts");

    println!("wrote {}/slider-ids.ts", gen_dir.display());
    println!("wrote {}/control-sab.ts", gen_dir.display());
    println!("wrote {}/lod-constants.ts", gen_dir.display());
}

fn render_slider_ids() -> String {
    let mut out = String::new();
    out.push_str("// @generated by `cargo run --bin gen-bindings` — DO NOT EDIT.\n");
    out.push_str("// Source of truth: src/wasm_api.rs (SLIDER_NAMES).\n");
    out.push_str("//\n");
    out.push_str("// Canonical slider ID table. Indices are stable across the SAB transport;\n");
    out.push_str("// main writes f32 values into CTRL_SLIDERS[idx], the worker dispatches\n");
    out.push_str("// via WorldHandle.set_slider_by_index(idx, value).\n\n");
    out.push_str("export const SLIDER_NAMES = [\n");
    for name in SLIDER_NAMES {
        out.push_str(&format!("  \"{}\",\n", name));
    }
    out.push_str("] as const;\n\n");
    out.push_str(&format!(
        "export const SLIDER_COUNT = {} as const;\n\n",
        SLIDER_COUNT
    ));
    out.push_str("export type SliderName = (typeof SLIDER_NAMES)[number];\n\n");
    out.push_str("/** Map slider name → canonical index, populated at module load. */\n");
    out.push_str("export const SLIDER_INDEX: Readonly<Record<string, number>> = Object.freeze(\n");
    out.push_str("  SLIDER_NAMES.reduce<Record<string, number>>((acc, n, i) => {\n");
    out.push_str("    acc[n] = i;\n");
    out.push_str("    return acc;\n");
    out.push_str("  }, {}),\n");
    out.push_str(");\n");
    out
}

/// v2.0.4 S1: emit LOD constants that both the sim worker (Rust) and the render
/// thread (TS) must agree on. Single source of truth: the Rust constants in
/// `src/wasm_api.rs`. Import from here in TS; do NOT hard-code these values.
fn render_lod_constants() -> String {
    let mut out = String::new();
    out.push_str("// @generated by `cargo run --bin gen-bindings` — DO NOT EDIT.\n");
    out.push_str("// Source of truth: src/wasm_api.rs (GRASS_LOD_BUDGET_AXIS).\n");
    out.push_str("//\n");
    out.push_str("// LOD constants shared between the sim worker (Rust) and renderer (TS).\n");
    out.push_str("// Single source: Rust → gen-bindings → this file → TS consumers.\n\n");
    out.push_str("/** v2.0.4 S1: clipmap budget axis in cells. The worker publishes at most\n");
    out.push_str(" * `GRASS_LOD_BUDGET_AXIS × GRASS_LOD_BUDGET_AXIS` grass bytes per slot.\n");
    out.push_str(" * Both the LOD switch threshold AND the window/texture clamp ceiling.\n");
    out.push_str(" * Raising it pushes downsampling later and allows a bigger window\n");
    out.push_str(" * before clamping. Sizes the snapshot slot (restart-scoped). */\n");
    out.push_str(&format!(
        "export const GRASS_LOD_BUDGET_AXIS = {} as const;\n",
        GRASS_LOD_BUDGET_AXIS
    ));
    out
}

