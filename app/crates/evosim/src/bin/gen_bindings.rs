#[cfg(test)]
mod tests {
    use super::*;

    /// Drift guard: the on-disk TS bindings must match what the generator
    /// produces from the current Rust sources. Fix-it command:
    /// `cargo run --bin gen-bindings`.
    type RenderFn = fn() -> String;

    #[test]
    fn bindings_in_sync() {
        let crate_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
        let pairs: &[(&str, RenderFn)] = &[
            ("../../web/src/generated/slider-ids.ts", render_slider_ids),
            ("../../web/src/generated/control-sab.ts", render_control_sab),
            (
                "../../web/src/generated/lod-constants.ts",
                render_lod_constants,
            ),
            (
                "../../web/src/generated/world-config.ts",
                render_world_config,
            ),
        ];
        for (rel_path, render) in pairs {
            let path = crate_dir.join(rel_path);
            let on_disk = std::fs::read_to_string(&path).unwrap_or_else(|e| {
                panic!(
                    "missing generated TS at {}: {e}. Run `cargo run --bin gen-bindings`.",
                    path.display()
                )
            });
            let expected = render();
            assert_eq!(
                on_disk, expected,
                "{} is out of sync with Rust sources. Run `cargo run --bin gen-bindings`.",
                rel_path
            );
        }
    }
}
